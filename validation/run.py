"""Run the validation cases and write the report into the documentation repository.

    python validation/run.py                 # every case
    python validation/run.py lamb_plate      # some cases (the others keep their last results)
    python validation/run.py --quick         # coarser studies, for a quick check
    python validation/run.py --docs DIR      # the docs/ folder of the documentation repository

Each case compares SolidOcean with an analytic solution (or another solver) and studies the convergence;
its checks set the exit code. The report is the page docs/validation/report.md of the documentation
repository (by default ../solidocean-docs, next to this one), its figures go to docs/images/validation/.
The sections of the report are kept in validation/sections.json, so a partial run updates only its own cases.
"""

from __future__ import annotations

import argparse
import datetime
import importlib
import json
import platform
import re
import sys
from pathlib import Path
import traceback

import common

CASES = ["lamb_plate", "zone_spectra", "free_sphere", "driven_bar", "lame_cylinder", "semi_infinite",
         "spreading_disk", "contact_stack", "three_omega", "fdtr", "hydro_vortex"]
GROUPS = [("Elastic waves and vibrations", ["lamb_plate", "zone_spectra", "free_sphere", "driven_bar"]),
          ("Statics", ["lame_cylinder"]),
          ("Heat transfer", ["semi_infinite", "spreading_disk", "contact_stack", "three_omega", "fdtr", "hydro_vortex"])]
SECTIONS = common.HERE / "sections.json"

FRONT_MATTER = """---
description: Every validation case with its equations, convergence studies, figures and checks.
icon: file-chart-column
---

"""
INTRO = """# Full report

SolidOcean is checked against exact solutions of elasticity and heat conduction. Every case builds ordinary
models (written to `validation/models/`, they open in the GUI) and solves them with the same solvers as the
command line; most also refine the mesh or the time step to show that the error falls at the rate theory
predicts for the elements (for quadratic elements: eigenfrequencies $h^4$, displacements and temperatures
$h^3$, stresses and fluxes $h^2$). Element sizes $h$ are measured mean edge lengths of the meshes.

This page is generated by `python validation/run.py` in the source repository (about three minutes); see
[Testing and validation](../technical/testing.md).
"""


def load_sections() -> dict:
    try:
        return json.loads(SECTIONS.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def gitbook(markdown: str, demote: bool = True) -> str:
    """Section markdown as GitBook renders it: headings one level down (the page has its own title), display
    math on lines of its own, inline math between double dollars, figures with captions, and one line per
    paragraph."""
    markdown = re.sub(r"^(#+) ", r"#\1 ", markdown, flags=re.M) if demote else markdown
    parts = re.split(r"(\$\$.+?\$\$)", markdown, flags=re.S)
    for i, part in enumerate(parts):
        if i % 2:
            parts[i] = "$$\n" + part[2:-2].strip() + "\n$$"
        else:
            parts[i] = re.sub(r"\$([^$\n]+(?:\n[^$\n]+)*?)\$", r"$$\1$$", part)
    text = re.sub(r"!\[(.*?)\]\((.*?)\)\n\*(.*?)\*\n",
                  r'<figure><img src="\2" alt="\1"><figcaption><p>\3</p></figcaption></figure>\n', "".join(parts))
    # a line continuing a paragraph: ordinary text, bold, or the tail of inline math ("$$ and so on")
    prose = re.compile(r"[^\s|#!$*-]|\*\*|\$\$\s*\S")
    lines = []
    for line in text.split("\n"):
        if lines and prose.match(line) and prose.match(lines[-1]) and lines[-1] != "$$":
            lines[-1] += " " + line
        else:
            lines.append(line)
    return "\n".join(lines)


def write_report(sections: dict) -> None:
    from solidocean import __version__
    out = [FRONT_MATTER + gitbook(INTRO, demote=False)]
    for group, names in GROUPS:
        present = [n for n in names if n in sections]
        if present:
            out.append(f"## {group}\n")
            out += [gitbook(sections[n]["markdown"]) for n in present]
    stamps = sorted({s["date"] for s in sections.values()})
    out.append(f"---\n*SolidOcean {__version__}; generated {', '.join(stamps)} on {platform.system()} "
               f"{platform.machine()}, Python {platform.python_version()}.*\n")
    report = common.DOCS / "validation" / "report.md"
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text("\n".join(out), encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cases", nargs="*", default=CASES, help=f"cases: {', '.join(CASES)}")
    ap.add_argument("--quick", action="store_true", help="coarser convergence studies")
    ap.add_argument("--docs", type=Path, default=common.DOCS,
                    help="the docs/ folder of the documentation repository (default: %(default)s)")
    args = ap.parse_args()
    if not args.docs.is_dir():
        ap.error(f"no documentation folder {args.docs}: clone solidocean-docs next to this repository, or give --docs")
    common.DOCS = args.docs.resolve()
    common.FIGURES = common.DOCS / "images" / "validation"
    unknown = [c for c in args.cases if c not in CASES]
    if unknown:
        ap.error(f"unknown case(s): {', '.join(unknown)}")
    sections = load_sections()
    failed = []
    for name in args.cases:
        print(f"{name} …", flush=True)
        try:
            report = importlib.import_module(name).run(quick=args.quick)
        except Exception:
            traceback.print_exc()
            failed.append(name)
            continue
        for c in report.checks:
            print(f"  {'ok  ' if c.ok else 'FAIL'} {c.text()}")
        print(f"  {report.seconds:.0f} s")
        if not report.ok:
            failed.append(name)
        sections[name] = {"title": report.title, "markdown": report.markdown(),
                          "date": datetime.date.today().isoformat()}
        common.FIGURES.mkdir(parents=True, exist_ok=True)
        SECTIONS.write_text(json.dumps(sections, indent=1, ensure_ascii=False), encoding="utf-8")
        write_report(sections)
    print("failed: " + ", ".join(failed) if failed else "all passed")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
